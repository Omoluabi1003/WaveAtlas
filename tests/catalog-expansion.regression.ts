import assert from 'node:assert/strict';
import { candidateNameKey, countryOrder, expansionAdmission, roundRobinCandidates } from '../lib/agents/catalog-expansion';
const valid={country:'NG',target:350,added:0,countryAdded:0,endpoint:'https://radio.example/live',sourceUuid:'abcdef01-1234-5678-9012-123456789012',hasHomepage:true,browserDecoded:true};
assert.equal(expansionAdmission(valid),undefined);
assert.equal(expansionAdmission({...valid,browserDecoded:false}),'browser_decoder_unverified');
assert.equal(expansionAdmission({...valid,endpoint:'http://radio.example/live'}),'https_required');
assert.equal(expansionAdmission({...valid,endpoint:'https://u:p@radio.example/live'}),'https_required');
assert.equal(expansionAdmission({...valid,sourceUuid:'missing'}),'missing_source_identity');
assert.equal(expansionAdmission({...valid,added:350}),'target_reached');
assert.equal(expansionAdmission({...valid,country:'US',countryAdded:20}),'country_cap');
assert.equal(expansionAdmission({...valid,countryAdded:119}),undefined);
assert.equal(expansionAdmission({...valid,countryAdded:120}),'country_cap');
assert.equal(expansionAdmission({...valid,hasHomepage:false}),'missing_broadcaster_homepage');
assert.equal(candidateNameKey('Rádio FM'),candidateNameKey('Radio FM'));
assert.notEqual(candidateNameKey('إذاعة أ'),candidateNameKey('إذاعة ب'));
assert.notEqual(candidateNameKey('北京电台'),candidateNameKey('上海电台'));
const ordered=countryOrder(['US','NG','GH','DE','FR'],new Map([['DE',8],['FR',0]]));
assert.equal(ordered[0],'NG');assert.equal(ordered[1],'GH');assert(ordered.indexOf('FR')<ordered.indexOf('DE'));
assert.deepEqual(roundRobinCandidates([[{name:'a'},{name:'b'}],[{name:'c'}],[{name:'d'}]]).map(s=>s.name),['a','c','d','b']);
assert.deepEqual(roundRobinCandidates([]),[]);
console.log('Catalog expansion: Nigeria priority, country fairness, hard target, HTTPS/source/decoder admission and Unicode deduplication passed');
